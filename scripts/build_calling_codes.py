"""Build the table in src/veil/detectors/_calling_codes.py.

    uv run --no-project --with phonenumbers==9.0.40 python scripts/build_calling_codes.py

For every country calling code the ITU has assigned, the shortest and longest
national number that can follow it, taken from the metadata of Google's
libphonenumber (through its Python port, `phonenumbers`, Apache-2.0). veil
itself has no dependencies: the table is generated once and committed.
"""

from __future__ import annotations

import phonenumbers
from phonenumbers import COUNTRY_CODE_TO_REGION_CODE, PhoneMetadata

KINDS = (
    "general_desc", "fixed_line", "mobile", "toll_free", "premium_rate", "shared_cost",
    "personal_number", "voip", "pager", "uan", "voicemail",
)  # fmt: skip


def main() -> None:
    print(
        f"# Generated by scripts/build_calling_codes.py from phonenumbers {phonenumbers.__version__}."
    )
    print("NATIONAL_LENGTHS: dict[str, tuple[int, int]] = {")
    for code, regions in sorted(COUNTRY_CODE_TO_REGION_CODE.items(), key=lambda item: str(item[0])):
        lengths: set[int] = set()
        for region in regions:
            metadata = PhoneMetadata.metadata_for_region_or_calling_code(code, region)
            for kind in KINDS:
                description = getattr(metadata, kind, None)
                if description is not None and description.possible_length:
                    lengths.update(n for n in description.possible_length if n > 0)
        if lengths:
            print(f'    "{code}": ({min(lengths)}, {max(lengths)}),')
    print("}")


if __name__ == "__main__":
    main()
